# Browser origins allowed to call the API (the Next.js frontend). Exact
# origins only; any other origin gets no CORS headers, so browsers block
# it. Development defaults to the local frontend; production has no
# default and must list its HTTPS origin(s).
CORS_ALLOWED_ORIGINS = env_list(
    "DJANGO_CORS_ALLOWED_ORIGINS",
    "http://localhost:3000,http://127.0.0.1:3000" if DEBUG else "",
)
for origin in CORS_ALLOWED_ORIGINS:
    if "*" in origin or origin.endswith("/"):
        raise ImproperlyConfigured(
            f"DJANGO_CORS_ALLOWED_ORIGINS: {origin!r} must be an exact "
            "origin such as https://app.example.com (no wildcard or path)."
        )
    if not DEBUG and not origin.startswith("https://"):
        raise ImproperlyConfigured(
            f"DJANGO_CORS_ALLOWED_ORIGINS: {origin!r} must use https "
            "when DJANGO_DEBUG is not true."
        )

